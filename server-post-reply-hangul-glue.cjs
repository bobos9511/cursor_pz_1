/** @param {string} word 교정 결과로 붙일 완성어 (한글 위주) */
function hangulSyllableGluePattern(word) {
  const chars = Array.from(String(word || "").trim());
  if (chars.length < 2) return null;
  const body = chars.map((ch) => ch.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("\\s*");
  return new RegExp(body, "g");
}

