/** 문자열 사전 중복 제거 + 길이 내림차순 */
function uniqueWordsSorted(words) {
  const seen = new Set();
  const out = [];
  for (const w of words) {
    const s = String(w || "").trim();
    if (!s || seen.has(s)) continue;
    seen.add(s);
    out.push(s);
  }
  out.sort((a, b) => b.length - a.length || a.localeCompare(b, "ko"));
  return out;
}

